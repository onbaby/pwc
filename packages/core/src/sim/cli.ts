import { mkdirSync, writeFileSync } from "node:fs";
import { cpus } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { SimGridArtifactSchema, ExhibitsArtifactSchema, PriorsArtifactSchema } from "@rot/contracts";
import { SIM } from "../constants.ts";
import { EXHIBITS } from "../exhibits.ts";
import { computeGrid, roundDeep } from "./grid.ts";
import { DISCLOSURE, LEDGER } from "./ledger.ts";
import { DEFAULT_PARAMS } from "./params.ts";
import { trainPrior } from "./prior.ts";

/** pnpm sim [--smoke] [--n 8000] [--workers 8] [--out artifacts] */
function arg(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../../..");
const smoke = process.argv.includes("--smoke");
const n = Number(arg("--n") ?? (smoke ? 1000 : 8000));
const workers = Number(arg("--workers") ?? Math.max(1, Math.min(cpus().length - 1, 9)));
const outDir = resolve(root, arg("--out") ?? "artifacts");

function write(rel: string, data: unknown): void {
  const path = resolve(outDir, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(data, null, 1) + "\n");
  console.log("wrote", path);
}

const t0 = Date.now();
console.log(`pnpm sim: ${n} subscribers per source, ${workers} worker(s), seed ${SIM.seed}${smoke ? " (smoke)" : ""}`);

write("exhibits.json", ExhibitsArtifactSchema.parse(EXHIBITS));
const prior = trainPrior(DEFAULT_PARAMS, SIM.seed, 4000);
write(
  "priors.json",
  PriorsArtifactSchema.parse(
    roundDeep({
      model: { sources: prior.sources, beta: prior.beta, tau: prior.tau, sigmaB: prior.sigmaB },
      trainedOn: { subscribers: 4000, seed: SIM.seed, note: "Layer A fitted on a synthetic training split (subscriber indices never scored). Synthetic, not client data." },
    }),
  ),
);

const grid = await computeGrid({
  subscribersPerSource: n,
  workers,
  onProgress: (d, t) => {
    if (d % 10 === 0 || d === t) process.stdout.write(`\r  tasks ${d}/${t}  ${((Date.now() - t0) / 1000).toFixed(0)}s`);
  },
});
process.stdout.write("\n");
const parsed = SimGridArtifactSchema.parse(roundDeep(grid));
write(smoke ? "sim_grid.smoke.json" : "sim_grid.json", parsed);
for (const w of parsed.meta.warnings) console.warn("WARNING:", w);

if (!smoke) {
  const ledgerMd = [
    "# Assumptions ledger (generated by `pnpm sim`; do not edit by hand)",
    "",
    "| Parameter | Value | Range | Source |",
    "|---|---|---|---|",
    ...LEDGER.map((e) => `| ${e.parameter} | ${e.value} | ${e.range} | ${e.source} |`),
    "",
  ].join("\n");
  const docs = resolve(root, "docs");
  mkdirSync(docs, { recursive: true });
  writeFileSync(resolve(docs, "assumptions.md"), ledgerMd);
  writeFileSync(resolve(docs, "disclosure.md"), `# Disclosure\n\n> ${DISCLOSURE}\n`);
  write("ledger.json", LEDGER);
}
console.log(`done in ${((Date.now() - t0) / 1000).toFixed(0)}s`);
